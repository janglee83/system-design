all_ids = {}
out_levels = []
for lv in LEVELS:
    lessons = []
    for les in lv["lessons"]:
        assert les["id"] not in all_ids, les["id"]
        all_ids[les["id"]] = lv["id"]
        for g in les["engine_gaps"]:
            assert g in GAPS, g
        planned = set(les["comps"]) - set(ENGINE_1A["components"]) | set(les["faults"]) - set(ENGINE_1A["faults"]) \
            | set(les["dyn"]) - set(ENGINE_1A["dynamic"]) | set(les["beh"])
        for p in planned:
            assert p in ENGINE_PLANNED["components"] + ENGINE_PLANNED["faults"] + ENGINE_PLANNED["dynamic"] + ENGINE_PLANNED["behaviors"], (les["id"], p)
        if les["engine_gaps"]:
            exp_ready = "blocked-by-gap"
        elif planned:
            exp_ready = "needs-1b"
        else:
            exp_ready = "ready-1a"
        if les["format"] == E:
            ready, upgrade = exp_ready, None
        else:
            ready = "not-needed"
            upgrade = exp_ready if (les["comps"] or les["engine_gaps"]) else None
        engine = dict(components=les["comps"], faults=les["faults"], dynamic=les["dyn"], behaviors=les["beh"],
                      calibration=les["cal"], nodeOverrides=les["nodeov"], metrics=les["metrics"], readiness=ready,
                      experimentUpgrade=upgrade)
        d = dict(id=les["id"], title_vi=les["title_vi"], title_en=les["title_en"], format=les["format"], minutes=les["minutes"],
                 difficulty=les["diff"], prerequisites=les["prerequisites"], concepts=les["concepts"], research=les["research"],
                 engine=engine, engine_gaps=les["engine_gaps"])
        if lv["id"] == "L0":
            d["draft"] = f"content/drafts/{les['id']}.md"
        lessons.append(d)
    o = {k: lv[k] for k in ("id", "title_vi", "title_en", "score")}
    o.update(entry_assumptions_vi=lv["entry_assumptions_vi"], entry_assumptions_en=lv["entry_assumptions_en"],
             outcomes_vi=lv["outcomes_vi"], outcomes_en=lv["outcomes_en"], exit_check=lv["exit_check"], lessons=lessons)
    out_levels.append(o)

# prerequisites exist and come earlier
order = [l["id"] for lv in out_levels for l in lv["lessons"]]
pos = {i: n for n, i in enumerate(order)}
for lv in out_levels:
    for l in lv["lessons"]:
        for p in l["prerequisites"]:
            assert p in pos, (l["id"], p)
            assert pos[p] < pos[l["id"]], ("prereq after lesson", l["id"], p)

ch_by_level = {lv["id"]: [] for lv in out_levels}
for c in CHALLENGES:
    for p in c["prerequisites"]:
        assert p in pos, (c["id"], p)
    for g in c["engine_gaps"]:
        assert g in GAPS, g
    kinds_planned = set(c["allowedKinds"]) - set(ENGINE_1A["components"])
    faults = {f["kind"] for m in c["modes"] for f in m["faults"]}
    planned = kinds_planned | (faults - set(ENGINE_1A["faults"]))
    c["readiness"] = "blocked-by-gap" if c["engine_gaps"] else ("needs-1b" if planned else "ready-1a")
    ch_by_level[c["level"]].append(c)
for lv in out_levels:
    lv["challenges"] = ch_by_level[lv["id"]]
    assert lv["challenges"], lv["id"]
    assert lv["exit_check"]["challenge"] in [c["id"] for c in lv["challenges"]], lv["id"]

